import { expect, test } from "bun:test";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { SqlTenantDirectory } from "../src/brain/tenancy";
import { defaultConfig } from "../src/config";
import { startLocalService, callLocalService } from "../src/local-service";
import { createPersonalAccessToken, revokePersonalAccessToken } from "../src/brain/access-tokens";
import { deviceAccessPaths, type TailscaleRunner } from "../src/device-installation";

test("service device gateway shares canonical evidence, caps grants, resumes, and revokes in-flight results", async () => {
 const root = await mkdtemp(join(tmpdir(), "manas-device-service-"));
 const config = { ...defaultConfig({}), stateRoot: join(root, "state") };
 const hostname = "brain.example.ts.net";
 let serve: Record<string, any> = {};
 let selected = true;
 const runner: TailscaleRunner = async (args) => {
  if (args[0] === "status") return JSON.stringify({ BackendState: "Running", Self: { ID: "self", DNSName: hostname + "." }, Peer: { key: { ID: "selected", HostName: "laptop" } } });
  if (args[0] === "whois") return JSON.stringify({ Node: { StableID: selected ? "selected" : "other", MachineAuthorized: true } });
  if (args.join(" ") === "serve status --json") return JSON.stringify(serve);
  if (args.at(-1) === "off") serve = {};
  else serve = { TCP: { "8443": { HTTPS: true } }, Web: { [hostname + ":8443"]: { Handlers: { "/manas": { Proxy: args.at(-1) } } } } };
  return "";
 };
 let service = await startLocalService({ config, repositoryRoot: join(root, "brain"), storePath: join(root, "store"), worker: false, tailscaleRunner: runner });
 const unix = deviceAccessPaths(config.stateRoot).socket;
 const request = async (token: string, method: string, params?: unknown, headers: Record<string, string> = {}) => fetch("http://localhost/mcp", { unix, method: "POST", headers: { authorization: "Bearer " + token, "content-type": "application/json", "x-forwarded-host": hostname + ":8443", "x-forwarded-proto": "https", "x-forwarded-for": "100.64.0.1", ...headers }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }) });
 const call = (token: string, name: string, args = {}) => request(token, "tools/call", { name, arguments: args }).then((response) => response.json());
 try {
  const run = promisify(execFile);
  await run("git", ["-C", service.engine.repository.root, "config", "user.name", "Test"]);
  await run("git", ["-C", service.engine.repository.root, "config", "user.email", "test@example.invalid"]);
  await service.engine.repository.putPage("notes/public.md", "Public evidence");
  const privatePage = await service.engine.repository.putPage("notes/private.md", "Private evidence");
  await service.engine.repository.setPageAccessLabels(privatePage.path, ["private"], privatePage.revision);
  const client = await createPersonalAccessToken(service.engine.store!, { name: "device", scopes: ["admin"] });
  await expect(callLocalService(config, "devices.enable", { deviceIds: ["selected"] }, { context: { scope: "admin", allowedAccessLabels: [] } })).rejects.toMatchObject({ code: "owner_access_required" });
  expect(await callLocalService(config, "devices.enable", { deviceIds: ["selected"] })).toMatchObject({ running: true, owned: true });
  expect((await request("invalid", "tools/list")).status).toBe(200);
  expect((await (await request("invalid", "tools/list")).json()).error).toBeDefined();
  const listed = await (await request(client.token, "tools/list")).json();
  expect(listed.result.tools.some((tool: { name: string }) => tool.name.startsWith("devices.") || tool.name.startsWith("admin.") || tool.name === "put_page" || tool.name === "search" || ["jobs.list", "sources.list", "agent.status", "cache.inspect", "skills.feedback.list"].includes(tool.name))).toBe(false);
  for (const name of ["jobs.list", "jobs.schedules", "sources.list", "agent.status", "cache.inspect", "skills.feedback.list"]) {
   expect((await call(client.token, name, name === "agent.status" ? { id: "unavailable" } : {})).error).toBeDefined();
   await expect(service.engine.operations.execute({ scope: "admin", tenantId: "local", allowedAccessLabels: [] }, name, name === "agent.status" ? { id: "unavailable" } : {})).rejects.toMatchObject({ code: "owner_access_required" });
  }
  let pages = await call(client.token, "list_pages");
  expect(JSON.parse(pages.result.content[0].text).pages.map((page: { path: string }) => page.path)).toEqual(["notes/public.md"]);
  expect((await call(client.token, "get_page", { path: "notes/private.md" })).error).toBeDefined();
  expect((await call(client.token, "list_pages", { tenantId: "other" })).error).toBeDefined();
  selected = false;
  expect((await request(client.token, "tools/list")).status).toBe(403);
  selected = true;
  expect((await request(client.token, "tools/list", undefined, { "tailscale-funnel-request": "?1" })).status).toBe(403);
  await service.close();
  service = await startLocalService({ config, repositoryRoot: join(root, "brain"), storePath: join(root, "store"), worker: false, tailscaleRunner: runner });
  expect(await callLocalService(config, "devices.status")).toMatchObject({ running: true, owned: true });
  expect((await call(client.token, "list_pages")).error).toBeUndefined();
  await callLocalService(config, "devices.enable", { deviceIds: ["selected"], visibility: ["private"] });
  pages = await call(client.token, "list_pages");
  expect(JSON.parse(pages.result.content[0].text).pages).toHaveLength(2);
  const directory = new SqlTenantDirectory(service.engine.store!);
  await directory.addUser("device-user");
  await service.engine.store!.query("INSERT INTO brain_tenants (id, name) VALUES ('local', 'Local') ON CONFLICT DO NOTHING");
  await service.engine.store!.query("INSERT INTO brain_registry (id, tenant_id, name) VALUES ($1, 'local', 'Brain') ON CONFLICT DO NOTHING", [(await service.engine.repository.getIdentity()).brainId]);
  await directory.grant({ userId: "device-user", tenantId: "local", role: "member", visibilityLabels: ["other"] });
  const delegated = await createPersonalAccessToken(service.engine.store!, { name: "delegated", userId: "device-user", scopes: ["read"] });
  expect(JSON.parse((await call(delegated.token, "list_pages")).result.content[0].text).pages).toHaveLength(1);
  await service.engine.store!.query("UPDATE brain_memberships SET visibility_labels = '[\"private\"]'::jsonb WHERE user_id = 'device-user'");
  expect(JSON.parse((await call(delegated.token, "list_pages")).result.content[0].text).pages).toHaveLength(2);
  await service.engine.store!.query("DELETE FROM brain_memberships WHERE user_id = 'device-user'");
  expect((await call(delegated.token, "list_pages")).error).toBeDefined();
  const capture = { text: "Juniper owner is Maya.", provenance: { sourceType: "user", sessionId: "remote", turnId: "turn" }, idempotencyKey: "remote:turn" };
  expect((await call(client.token, "memory.remember", capture)).error).toBeDefined();
  await callLocalService(config, "devices.enable", { deviceIds: ["selected"], write: true });
  const captured = await call(client.token, "memory.remember", capture);
  expect(captured.error).toBeUndefined();
  const first = JSON.parse(captured.result.content[0].text);
  expect(JSON.parse((await call(client.token, "memory.remember", capture)).result.content[0].text)).toMatchObject({ id: first.id, revision: first.revision, commit: first.commit, replayed: true });
  expect((await call(delegated.token, "memory.remember", capture)).error).toBeDefined();
  // Delay a real catalog operation to change authorization while the result is being produced.
  let entered!: () => void;
  const started = new Promise<void>((resolve) => { entered = resolve; });
  let release!: () => void;
  const wait = new Promise<void>((resolve) => { release = resolve; });
  service.engine.operations.register({ name: "test.delayed", description: "Delayed evidence for revocation test", requiredScope: "read", trustBoundary: "remote-safe", inputSchema: {}, outputSchema: {}, execute: async () => { entered(); await wait; return { secret: "must be suppressed" }; } });
  await callLocalService(config, "devices.enable", { deviceIds: ["selected"] });
  const pending = call(client.token, "test.delayed");
  await started;
  await revokePersonalAccessToken(service.engine.store!, client.record.id);
  release();
  expect((await pending).error).toBeDefined();
  await callLocalService(config, "devices.disable");
  expect(await callLocalService(config, "devices.status")).toMatchObject({ running: false, installed: false });
  expect(serve).toEqual({});
  const configPath = join(root, "config.json");
  await writeFile(configPath, JSON.stringify(config));
  const cli = await run(process.execPath, ["src/cli.ts", "devices", "status", "--config", configPath, "--json"]);
  expect(JSON.parse(cli.stdout).data).toMatchObject({ running: false, installed: false });
  await callLocalService(config, "devices.enable", { deviceIds: ["selected"] });
  await service.close();
  serve.Web[hostname + ":8443"].Handlers["/unrelated"] = { Text: "preserved" };
  const edited = structuredClone(serve);
  service = await startLocalService({ config, repositoryRoot: join(root, "brain"), storePath: join(root, "store"), worker: false, tailscaleRunner: runner });
  expect(await callLocalService(config, "devices.status")).toMatchObject({ running: false, owned: false, error: { code: "device_configuration_conflict" } });
  expect(await callLocalService(config, "service.status")).toMatchObject({ running: true });
  await expect(callLocalService(config, "devices.disable")).rejects.toMatchObject({ code: "device_configuration_conflict" });
  expect(serve).toEqual(edited);
 } finally { await service.close(); await rm(root, { recursive: true, force: true }); await rm(join(unix, ".."), { recursive: true, force: true }); }
}, 30_000);
