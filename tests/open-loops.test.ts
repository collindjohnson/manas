import { test, expect } from "bun:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { BrainRepository } from "../src/brain/repository";
import { openPgliteBrainStore } from "../src/brain/store";
import { indexBrainRepository, searchVerifiedHybridBrainRepository } from "../src/brain/pglite-indexer";
import { remember, forget } from "../src/brain/memory";
import { putOpenLoop, setOpenLoopStatus, getOpenLoop, listOpenLoops } from "../src/brain/open-loops";
import { createFullOperationRegistry } from "../src/brain/operation-catalog";
const owner = { scope: "admin" as const, principal: "owner" };
test("open loops persist, enforce revisions, and replay without undoing a later status", async () => {
 const root = await mkdtemp(join(tmpdir(), "manas-loops-")), repository = new BrainRepository(join(root, "brain")), store = await openPgliteBrainStore();
 try {
  await repository.initialize();
  for (const [key, value] of [["user.name", "Test"], ["user.email", "test@example.invalid"]]) await promisify(execFile)("git", ["-C", repository.root, "config", key!, value!]);
  const memory = await remember(repository, owner, { text: "Maya will send the Juniper proposal on Friday.", idempotencyKey: "fact", provenance: { sourceType: "user" }, visibility: ["private"] });
  await indexBrainRepository(store, repository);
  const evidence = (await searchVerifiedHybridBrainRepository(store, repository, "Juniper")).map((hit) => hit.citation);
  const input = { title: "Send Juniper proposal", participants: ["Maya"], dueAt: "2030-01-01T00:00:00Z", evidence, idempotencyKey: "loop" };
  const first = await putOpenLoop(repository, owner, input);
  const reopened = new BrainRepository(repository.root);
  expect(await getOpenLoop(reopened, owner, first.id)).toMatchObject({ title: input.title, status: "open", visibility: ["private"] });
  expect((await listOpenLoops(reopened, { scope: "read", allowedAccessLabels: [] })).items).toEqual([]);
  await expect(putOpenLoop(repository, owner, { ...input, title: "Changed" })).rejects.toMatchObject({ code: "idempotency_conflict" });
  await expect(setOpenLoopStatus(repository, owner, { id: first.id, expectedRevision: "stale", status: "done", idempotencyKey: "bad" })).rejects.toMatchObject({ code: "revision_conflict" });
  const closed = await setOpenLoopStatus(repository, owner, { id: first.id, expectedRevision: first.revision, status: "done", idempotencyKey: "done" });
  expect(await putOpenLoop(repository, owner, input)).toMatchObject({ id: first.id, currentStatus: "done", originalStatus: "open", replayed: true, revision: closed.revision });
  expect((await listOpenLoops(repository, owner, { status: "open" })).items).toEqual([]);
  expect((await listOpenLoops(repository, owner, { participant: "maya", status: "done" })).items).toHaveLength(1);
  await forget(repository, owner, { id: memory.id, expectedRevision: memory.revision, idempotencyKey: "withdraw" });
  await indexBrainRepository(store, repository);
  expect((await listOpenLoops(repository, owner)).items).toEqual([]);
  const stale = await listOpenLoops(repository, owner, { includeStale: true });
  expect(stale.items).toMatchObject([{ id: first.id, freshness: "stale" }]);
  expect(JSON.stringify(stale)).not.toContain("Juniper");
  await expect(setOpenLoopStatus(repository, owner, { id: first.id, expectedRevision: closed.revision, status: "open", idempotencyKey: "reopen" })).rejects.toThrow();
  const cancelled = await setOpenLoopStatus(repository, owner, { id: first.id, expectedRevision: closed.revision, status: "cancelled", idempotencyKey: "cancel" });
  expect(cancelled.status).toBe("cancelled");
  const operations = createFullOperationRegistry({ repository, store });
  const path = (await repository.snapshot()).pages.find((page) => page.id === first.id)!.path;
  await expect(operations.execute({ scope: "read", allowedAccessLabels: ["private"] }, "get_page", { path })).rejects.toMatchObject({ code: "derived_record_access_required" });
  const exported = await operations.execute({ scope: "read", allowedAccessLabels: ["private"] }, "export_brain", {});
  expect(JSON.stringify(exported)).not.toContain("Send Juniper");
  expect(await searchVerifiedHybridBrainRepository(store, repository, "Juniper")).toEqual([]);
 } finally { await store.close(); await rm(root, { recursive: true, force: true }); }
}, 20000);
